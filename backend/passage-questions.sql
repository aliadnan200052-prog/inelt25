/* ═══════════════════════════════════════════════════════════════════════
   أسئلة قطعة واحدة — قراءة فقط
   ───────────────────────────────────────────────────────────────────────
   غيّر الكلمات في السطر المعلَّم أدناه إلى بداية القطعة التي تريدها، ثم
   شغّل. يعرض كل أسئلتها بأرقامها وإجاباتها الصحيحة، لتقارنها وتعرف أيّها
   زائد. لا يعدّل شيئاً.

   لحذف سؤال زائد لا تحذفه من هنا: افتح لوحة الإدارة، أو عطّله بـ
       update public.questions set active = false where id = <الرقم>;
   ═══════════════════════════════════════════════════════════════════════ */
select id,
       left(question, 80)                    as السؤال,
       options ->> correct_answer            as الإجابة,
       correct_answer + 1                    as رقم_الإجابة,
       coalesce(active, true)                as مفعّل
  from public.questions
 where section = 'Reading Comprehension'
   and passage ilike '%Who is your best friend%'   -- ← غيّر هذه
 order by id;
