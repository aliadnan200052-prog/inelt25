"""
Build js/vocab/bank.js from items.txt, pseudowords.txt and ranking.json.

  python build_ranking.py > ranking.json
  python build_bank.py ranking.json > ../../js/vocab/bank.js

Every real item's band comes from the rank of its family in ranking.json.
Items whose family is ranked above 20,000 (or not found) are rejected.
"""
import json, re, sys, datetime
from wordfreq import word_frequency, top_n_list
from lemminflect import getAllLemmas

BANDS = [(1, 1000), (1001, 2000), (2001, 3000), (3001, 4000), (4001, 5000),
         (5001, 6000), (6001, 8000), (8001, 10000), (10001, 15000), (15001, 20000)]
POS = {"n": "noun", "v": "verb", "adj": "adjective", "adv": "adverb"}

def band_of(rank):
    for i, (a, b) in enumerate(BANDS, 1):
        if a <= rank <= b:
            return i
    return None

def edit1(a, b):
    if abs(len(a) - len(b)) > 1: return False
    if len(a) == len(b): return sum(x != y for x, y in zip(a, b)) == 1
    if len(a) > len(b): a, b = b, a
    for i in range(len(b)):
        if a == b[:i] + b[i+1:]: return True
    return False

def main():
    ranking = json.load(open(sys.argv[1]))
    member = {}
    for e in ranking:
        for m in e["members"]:
            member.setdefault(m, e)
        member.setdefault(e["head"], e)
    items, rejected = [], []
    seen = set()
    for line in open(__file__.replace("build_bank.py", "items.txt"), encoding="utf-8"):
        line = line.strip()
        if not line or line.startswith("#"): continue
        parts = line.split("|")
        word, pos, defn, ex, ar = parts[:5]
        awl = len(parts) > 5 and parts[5] == "awl"
        assert pos in POS, line
        assert "*" in ex, line
        assert word.lower() not in defn.lower().split(), ("definition uses target", word)
        if word in seen: raise SystemExit("duplicate " + word)
        seen.add(word)
        fam = member.get(word)
        b = band_of(fam["rank"]) if fam else None
        if not b:
            rejected.append(word); continue
        members = [m for m in fam["members"] if m != word][:12]
        items.append({"id": word, "w": word, "pos": POS[pos], "band": b, "rank": fam["rank"],
                      "head": fam["head"], "fam": members, "def": defn, "ex": ex, "ar": ar,
                      "awl": awl})
    # pseudowords
    common = [w for w in top_n_list("en", 30000) if w.isalpha()]
    by_len = {}
    for w in common: by_len.setdefault(len(w), []).append(w)
    pseudo, prej = [], []
    for line in open(__file__.replace("build_bank.py", "pseudowords.txt"), encoding="utf-8"):
        if line.startswith("#"): continue
        for w in line.split():
            if w.endswith("?"):           # marked by the author as a real word -> excluded on purpose
                prej.append((w[:-1], "author-flagged real word")); continue
            if word_frequency(w, "en") > 0: prej.append((w, "in corpus")); continue
            if getAllLemmas(w): prej.append((w, "in lexicon")); continue
            near = next((c for L in (len(w)-1, len(w), len(w)+1) for c in by_len.get(L, []) if edit1(w, c)), None)
            if near: prej.append((w, "one letter from " + near)); continue
            pseudo.append(w)
    print("// GENERATED by tools/vocab/build_bank.py on %s — do not edit by hand." % datetime.date.today())
    print("// %d real items, %d pseudowords. Rejected real items: %s" % (len(items), len(pseudo), rejected or "none"))
    print("// Rejected pseudoword candidates: " + "; ".join("%s (%s)" % r for r in prej))
    print("(function (root) {")
    print("  var BANK = " + json.dumps({"bands": [{"id": i, "from": a, "to": b, "size": b - a + 1} for i, (a, b) in enumerate(BANDS, 1)],
                                          "items": items, "pseudowords": pseudo,
                                          "source": "wordfreq 3.x (aggregated corpora) + lemminflect lexicon; families approximated by tools/vocab/build_ranking.py"},
                                         ensure_ascii=False, indent=0) + ";")
    print("  if (typeof module !== 'undefined' && module.exports) module.exports = BANK; else root.VSE_BANK = BANK;")
    print("})(this);")
    from collections import Counter
    c = Counter(i["band"] for i in items)
    print("// items per band: " + ", ".join("B%d=%d" % (k, c[k]) for k in sorted(c)), file=sys.stderr)
    print("// pseudowords kept: %d; rejected: %s" % (len(pseudo), prej), file=sys.stderr)

if __name__ == "__main__":
    main()
