/* ═══════════════════════════════════════════════════════════════════════
   مصمّم الامتحانات · service worker  (GENERATED by exam-designer/vite.config.ts
   from exam-designer/sw/exam-sw.js — edit the template, not /exam-sw.js)

   Served from the site root so it can control /exam (the site has no
   trailing slashes, so a worker inside /exam/ could not).
   - The page (/exam) is fetched from the network first; the cached copy is
     only an offline fallback, so a deploy takes effect immediately.
   - Built assets under /exam/ are content-hashed, so they are served from
     the cache and precached on install: the app works fully offline.
   ═══════════════════════════════════════════════════════════════════════ */

const CACHE = 'exam-designer-__VERSION__';
const PAGE = '/exam';
const ASSETS = __ASSETS__;

self.addEventListener('install', (event) => {
  event.waitUntil(
    caches
      .open(CACHE)
      .then((c) => Promise.all([PAGE, ...ASSETS].map((u) => c.add(u).catch(() => null))))
      .then(() => self.skipWaiting()),
  );
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) => Promise.all(keys.filter((k) => k.startsWith('exam-designer-') && k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});

self.addEventListener('fetch', (event) => {
  const req = event.request;
  if (req.method !== 'GET') return;
  const url = new URL(req.url);
  if (url.origin !== self.location.origin) return;

  if (req.mode === 'navigate' && (url.pathname === PAGE || url.pathname === PAGE + '/')) {
    event.respondWith(
      fetch(req)
        .then((res) => {
          const copy = res.clone();
          caches.open(CACHE).then((c) => c.put(PAGE, copy)).catch(() => {});
          return res;
        })
        .catch(() => caches.match(PAGE)),
    );
    return;
  }

  if (url.pathname.startsWith('/exam/')) {
    event.respondWith(
      caches.match(req).then(
        (hit) =>
          hit ||
          fetch(req).then((res) => {
            if (res.ok) {
              const copy = res.clone();
              caches.open(CACHE).then((c) => c.put(req, copy)).catch(() => {});
            }
            return res;
          }),
      ),
    );
  }
});
